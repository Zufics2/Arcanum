import uuid

from django.conf import settings
from django.db import models

from accounts.avatars import random_default_avatar


def avatar_upload_to(instance: "Profile", filename: str) -> str:
    return f"avatars/{uuid.uuid4().hex}"


class Profile(models.Model):
    """Per-user crypto material and appearance.

    - ``salt``: 16 random bytes generated by the client, public by design.
    - ``encrypted_master_key``: the user's masterKey encrypted with userKey
      (derived from the password in the browser), ``iv || ciphertext`` in base64.
    - ``default_avatar``: name of a built-in icon, assigned randomly at registration.
    - ``encrypted_avatar``: optional custom picture, encrypted with masterKey in the browser,
      so the server never sees the image.
    - ``recovery_*``: lets the user reset a forgotten password with a recovery key.
    """

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="profile",
    )
    salt = models.CharField(max_length=32)
    encrypted_master_key = models.TextField()
    default_avatar = models.CharField(max_length=32, default=random_default_avatar)
    encrypted_avatar = models.FileField(upload_to=avatar_upload_to, null=True, blank=True)
    # Recovery key (optional). The key itself never reaches the server:
    # - recovery_auth_hash: Django hash of a value derived from the key (proves knowledge of it);
    # - recovery_encrypted_master_key: the same masterKey, encrypted with another key derived from it.
    recovery_auth_hash = models.CharField(max_length=128, blank=True, default="")
    recovery_encrypted_master_key = models.TextField(blank=True, default="")

    @property
    def has_recovery_key(self) -> bool:
        return bool(self.recovery_auth_hash)

    def __str__(self) -> str:
        return f"Profile({self.user.username})"
